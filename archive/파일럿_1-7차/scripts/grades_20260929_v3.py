def lookup(table, qid, cond):
    g = table.get(qid)
    if not g:
        return None
    return g.get(cond) or (g.get("CD") if cond in CD else None) or g.get("*")


def grade_run(tag, pattern, override, out_name):
    rows = []
    patterns = [pattern] if isinstance(pattern, str) else pattern   # 여러 패턴(목록)도 받는다(6차부터)
    files = sorted({f for pat in patterns for f in glob.glob(str(ROOT / "results" / pat))})
    for f in files:
        for line in open(f, encoding="utf-8"):
            r = json.loads(line)
            if r["qid"] not in G_V1:      # 시나리오 설정 턴(A0 등)은 집계 제외
                continue
            v, err, memo = lookup(override, r["qid"], r["condition"]) or lookup(G_V1, r["qid"], r["condition"])
            # 틀린 전제가 없는 역할 질문인데 '그렇지 않소'로 시작한 답 (v2 말버릇이 남았는지)
            tic = (r["speaker"] == "character" and r["qid"] not in PREMISE
                   and r["answer"].startswith("그렇지 않소"))
            rows.append({"set": r["kind"], "qid": r["qid"], "condition": r["condition"], "top_k": r.get("top_k", ""),
                         "prompt_version": r.get("prompt_version", ""), "category": r["category"],
                         "question": r["question"], "answer": r["answer"],
                         "판정": v, "오류 유형": err, "메모": memo, "첫마디 '그렇지 않소'": "Y" if tic else "",
                         "사람 확인": "", "retrieval_hit": r["auto"]["retrieval_hit"],
                         "context_ids": " ".join(r["context_ids"]) if len(r["context_ids"]) < 10 else "전체"})
    out = ROOT / "results" / out_name
    with open(out, "w", encoding="utf-8-sig", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    by = defaultdict(Counter)
    for r in rows:
        part = "단발" if r["set"] == "single" else "시나리오"
        by[(r["condition"], part)][r["판정"]] += 1
    print(f"== {tag}: {out.name}")
    for cond in ("B", "C", "D1", "D2"):
        if not by[(cond, "단발")]:
            continue
        ok = {p: by[(cond, p)]["정답"] + by[(cond, p)]["적절한 보류"] for p in ("단발", "시나리오")}
        leak = sum(by[(cond, p)]["누설"] for p in ("단발", "시나리오"))
        role = [r for r in rows if r["condition"] == cond and r["qid"] not in PREMISE
                and (r["set"] != "single" or r["qid"] in ("Q1", "Q2", "Q3"))]
        tics = sum(r["첫마디 '그렇지 않소'"] == "Y" for r in role)
        print(f"{cond} 단발 맞음 {ok['단발']}/25, 역할 맞음 {ok['시나리오']}/30, 누설 {leak}, "
              f"불필요한 '그렇지 않소' {tics}/{len(role)}")
        for part in ("단발", "시나리오"):
            print("   ", part, dict(by[(cond, part)]))


def main():
    for run in RUNS:
        grade_run(*run)


if __name__ == "__main__":
    main()
