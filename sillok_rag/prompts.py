def context_block(chunks: list[dict]) -> str:
    """검색된 청크의 우리 번역문을 머리말(청크 ID·출처·기록일·화자)과 함께 넣는다."""
    parts = []
    for c in chunks:
        header = f"[{c['chunk_id']} · {cite(c)} · 기록일 {c['record_date'] or '총서(날짜 없음)'} · 화자 {c['speaker']}]"
        parts.append(f"{header}\n{c['translation']}")
    return "[자료]\n" + "\n\n".join(parts)


def known_facts_block(facts: list[dict]) -> str:
    """장면마다 사람이 적어 둔 '이 인물이 이미 아는 사실'. 검색·시점 필터와 상관없이 항상 넣는다."""
    lines = [f"- {f['fact']} (근거 {f['source']})" for f in facts]
    return "[이 인물이 이 시점에 아는 사실]\n" + "\n".join(lines)


