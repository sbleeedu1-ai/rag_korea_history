def premise_note(items: list[dict]) -> str:
    lines = [f"- 전제: {i['claim']} / 자료({i['chunk']}): \"{i['quote']}\" / 바른 내용: {i['correct']}" for i in items]
    return PREMISE_NOTE.format(items="\n".join(lines))


def rerank_messages(question: str, chunks: list[dict], k: int, check: bool = False,
                    scene: str | None = None) -> list[dict]:
    parts = [f"ID: {c['chunk_id']}\n{c['title_ko']} · 화자 {c['speaker']} · 기록일 {c['record_date'] or '총서(날짜 없음)'}\n"
             f"{c['translation']}" for c in chunks]
    user = f"[질문]\n{question}\n\n[후보]\n" + "\n\n".join(parts)
    # 역할 대화: 질문 속 '오늘'·'상소'·'그 명단'이 가리키는 장면(작업기록 [183]). 장면 설명은 판정할 전제가 아니다.
    if scene:
        user = f"[장면 — 질문이 오가는 상황. 질문 속 '오늘'·'그' 같은 말은 이 장면을 가리킴]\n{scene}\n\n" + user
    rules = (RERANK_CHECK_RULES if check else RERANK_RULES).format(k=k)
    return [{"role": "system", "content": rules}, {"role": "user", "content": user}]


