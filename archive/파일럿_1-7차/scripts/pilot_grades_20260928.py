# 2026-09-29 사용자가 결론을 좌우하는 10문항을 실록과 대조해 모두 동의함.
# Q7은 판정에는 동의하되 질문 자체가 헷갈릴 수 있다고 봄 → 다음 실행부터 문구 수정.
HUMAN_CHECK = {q: "동의" for q in ("B8", "B9", "C2", "C7", "A6", "A8", "C9", "C10", "C8")}
HUMAN_CHECK["Q7"] = "동의(질문 모호, 문구 수정)"


def grade(qid, cond):
    g = G[qid]
    return g.get(cond) or (g.get("CD") if cond in CD else None) or g["*"]


def main():
    out = ROOT / "results" / "pilot_20260928_grades.csv"
    rows = []
    for f in sorted(glob.glob(str(ROOT / "results" / "20260928-*.jsonl"))):
        for line in open(f, encoding="utf-8"):
            r = json.loads(line)
            if r["qid"] not in G:      # 시나리오 설정 턴(A0 등)은 집계 제외
                continue
            v, err, memo = grade(r["qid"], r["condition"])
            rows.append({"set": r["kind"], "qid": r["qid"], "condition": r["condition"], "category": r["category"],
                         "question": r["question"], "answer": r["answer"],
                         "판정": v, "오류 유형": err, "메모": memo, "사람 확인": HUMAN_CHECK.get(r["qid"], ""),
                         "retrieval_hit": r["auto"]["retrieval_hit"], "context_ids": " ".join(r["context_ids"]) if len(r["context_ids"]) < 10 else "전체"})
    with open(out, "w", encoding="utf-8-sig", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    by = defaultdict(Counter)
    errs = defaultdict(Counter)
    for r in rows:
        part = "단발" if r["set"] == "single" else "시나리오"
        by[(r["condition"], part)][r["판정"]] += 1
        by[(r["condition"], "전체")][r["판정"]] += 1
        if r["오류 유형"]:
            errs[r["condition"]][r["오류 유형"]] += 1
    for cond in ("A", "B", "C", "D1", "D2"):
        for part in ("단발", "시나리오", "전체"):
            print(cond, part, dict(by[(cond, part)]))
        print(cond, "오류", dict(errs[cond]))
    print(out)


if __name__ == "__main__":
    main()
